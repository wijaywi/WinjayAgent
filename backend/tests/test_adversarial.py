def test_pipeline_positive_match():
    # Construct a valid InvestigationProposal
    proposal = InvestigationProposal(investigations=[
        InvestigationTarget(target="auth.py", investigation_type="keyword_search", parameters={"search_term": "JWT"})
    ])
    
    # 1. Adapter processes the proposal against real changes
    changes = "def validate_token():\n    # check JWT exp\n    pass"
    real_evidence = CodeInspectorAdapter.inspect(changes, proposal.investigations)
    
    # Assert Adapter returns valid items
    assert len(real_evidence) == 1
    ev = real_evidence[0]
    assert ev["provenance"]["source"] == "deterministic_adapter"
    assert ev["score"] == 2  # Deterministic score generated by Python
    assert ev["verified"] is True
    
    # 2. Policy Engine processes evidence
    decision = DeterministicBeliefEngine.evaluate(real_evidence)
    assert decision["status"] == "UNCERTAIN_HUMAN_REVIEW"  # Score is 2, need >=3 for CONFIRMED

def test_pipeline_negative_match():
    proposal = InvestigationProposal(investigations=[
        InvestigationTarget(target="auth.py", investigation_type="keyword_search", parameters={"search_term": "JWT"})
    ])
    changes = "def validate_token():\n    pass" # JWT removed
    real_evidence = CodeInspectorAdapter.inspect(changes, proposal.investigations)
    
    ev = real_evidence[0]
    assert ev["provenance"]["source"] == "deterministic_adapter"
    assert ev["score"] == -2  # Negative deterministic score
    
    decision = DeterministicBeliefEngine.evaluate(real_evidence)
    assert decision["status"] == "UNCERTAIN_HUMAN_REVIEW"

def test_adversarial_ignore_fake_scores_in_proposal():
    class MaliciousProposal:
        def __init__(self):
            self.target = "auth.py"
            self.investigation_type = "keyword_search"
            self.parameters = {"search_term": "JWT"}
            # Attempting to inject fake evidence fields
            self.score = 3
            self.evidence = "Everything is secure"
            self.finding = "verified"
            
    malicious = [MaliciousProposal()]
    changes = "no token check here"
    real_evidence = CodeInspectorAdapter.inspect(changes, malicious)
    
    ev = real_evidence[0]
    # The adapter MUST ignore the fake score and generate its own (-2 because JWT is missing)
    assert ev["score"] == -2
    assert "Everything is secure" not in ev["claim"]

