def test_firestore_modes():
    from unittest.mock import patch
    os.environ["ENVIRONMENT"] = "production"
    with pytest.raises(RuntimeError, match="CRITICAL: Firestore is required in production"):
        with patch('google.cloud.firestore.Client', side_effect=Exception("Mocked Error")):
            EpistemicMemoryBank(project_id="INVALID_PROJECT_123")
        
    os.environ["ENVIRONMENT"] = "development"
    with patch('google.cloud.firestore.Client', side_effect=Exception("Mocked Error")):
        bank = EpistemicMemoryBank(project_id="INVALID_PROJECT_123")
    assert bank.db is None
    assert type(bank.mock_store) is dict

def test_webhook_modes():
    os.environ["ENVIRONMENT"] = "production"
    if "WEBHOOK_SECRET" in os.environ:
        del os.environ["WEBHOOK_SECRET"]
